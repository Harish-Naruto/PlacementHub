// Report contract for GitHub-based resume verification.
// GitHub evidence is secondary: it never changes an assessment score and never proves proficiency.

export type ClaimStatus =
    | 'supported'
    | 'partially_supported'
    | 'insufficient_evidence'
    | 'needs_review'
    | 'not_accessible'
    | 'not_checked';

export type EvidenceType =
    | 'language_statistics' // discovery signal only
    | 'dependency'
    | 'source_code'
    | 'configuration'
    | 'file_presence'
    | 'repository_metadata';

export type EvidenceStrength = 'weak' | 'moderate' | 'strong';

export interface Evidence {
    evidence_type: EvidenceType;
    repository: string; // owner/name
    path: string | null;
    url: string | null; // pinned to commit_sha when known
    commit_sha: string | null;
    observation: string; // generated by us; never copied from repository text
    strength: EvidenceStrength;
}

export interface TechnologyResult {
    technology: string;
    status: ClaimStatus;
}

export interface Claim {
    claim_type: 'skill' | 'project';
    claim: string;
    status: ClaimStatus;
    confidence: null; // deliberately not scored
    resume_references: string[]; // where in the resume the claim came from
    evidence: Evidence[];
    limitations: string[];
    technologies?: TechnologyResult[]; // project claims only
    repository?: string | null; // project claims only
}

export type RepoResolution = 'linked_url' | 'name_match' | 'name_match_approximate' | 'additional';
export type RepoStatus = 'examined' | 'partially_examined' | 'not_accessible';

export interface RepositorySummary {
    full_name: string;
    url: string;
    resolution: RepoResolution;
    status: RepoStatus;
    default_branch: string | null;
    commit_sha: string | null;
    is_fork: boolean;
    pushed_at: string | null;
    languages: Record<string, number>; // bytes per language; context only
    files_examined: number;
    notes: string[];
}

export interface VerificationReport {
    github_profile: {
        username: string;
        profile_url: string;
        access_mode: 'public';
        username_source: UsernameSource;
        checked_at: string;
    };
    repositories: RepositorySummary[];
    claims: Claim[];
    summary: Record<ClaimStatus, number>;
    limitations: string[];
    /** True when a rate limit, request budget or listing failure stopped collection early. */
    incomplete: boolean;
    assessment_score_changed: false;
}

export type UsernameSource = 'request' | 'resume_profile_link' | 'student_profile' | 'resume_repository_link';
